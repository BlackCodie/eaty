    if (amt('vitD') >= 2.5) add('vitaminD', 'support', amt('vitD') >= 10 ? 2 : 1, 'good', 'strong', `${Math.round(amt('vitD') * 10) / 10} µg vitamin D — the precursor of the hormone calcitriol.`, ['efsa-vitd']);
