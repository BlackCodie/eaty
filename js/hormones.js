    if (caf >= 40) add('melatonin', 'down', caf >= 150 ? 2 : 1, 'caution', 'moderate', 'Caffeine in the evening delays the melatonin rise by around 40 minutes and shortens deep sleep.', ['burke-2015', 'drake-2013']);
